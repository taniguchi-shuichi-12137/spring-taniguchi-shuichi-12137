package com.example.demo.controller.model;

public class Item {
	
	private String name;
	private Integer price;
	
	public Item() {
		
		
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public Integer getPrice() {
		return price;
	}

	public void setPrice(Integer price) {
		this.price = price;
	}

}
